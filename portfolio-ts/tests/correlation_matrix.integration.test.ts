import { describe, expect, test } from "bun:test";
import { SQL } from "bun";

const DB_URL = process.env.PORTFOLIO_DB_URL;
const MAYBE_SKIP = DB_URL ? describe : describe.skip;

const AS_OF = "2026-01-06";

// Temp tables mirror the columns portfolio_correlation_matrix_sql() reads:
// transactions.asset and prices.ticker are VARCHAR in schema.sql.
const DDL = {
  transactions: `
    CREATE TEMP TABLE transactions (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      date DATE NOT NULL,
      asset VARCHAR NOT NULL,
      action VARCHAR NOT NULL,
      quantity DOUBLE PRECISION NOT NULL,
      asset_type VARCHAR,
      price DOUBLE PRECISION,
      currency VARCHAR,
      fees DOUBLE PRECISION,
      fee_currency VARCHAR,
      exchange VARCHAR,
      data_source VARCHAR,
      account VARCHAR,
      exchange_group_id TEXT,
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMP
    ) ON COMMIT DROP
  `,
  prices: `
    CREATE TEMP TABLE prices (
      date DATE NOT NULL,
      ticker VARCHAR NOT NULL,
      price DOUBLE PRECISION NOT NULL,
      PRIMARY KEY (date, ticker)
    ) ON COMMIT DROP
  `,
};

// ── Hand-calculated fixture: two tickers, six prices → five daily returns ──
//
// AAA prices: 100.0 → 110.0 → 104.5 → 125.4 → 125.4 → 106.59
//   returns x = [+0.10, -0.05, +0.20,  0.00, -0.15]
// BBB prices:  50.0 →  52.5 →  57.75 → 60.6375 → 54.57375 → 54.57375
//   returns y = [+0.05, +0.10, +0.05, -0.10,  0.00]
//
// Pearson on simple returns, n = 5:
//   Σx  = 0.10   Σy  = 0.10
//   Σxy = 0.01
//   Σx² = 0.075  Σy² = 0.025
//   numerator   = n·Σxy − Σx·Σy = 5·0.01 − 0.01 = 0.04            (= 1/25)
//   denom_x     = n·Σx² − (Σx)² = 0.375 − 0.01 = 0.365            (= 73/200)
//   denom_y     = n·Σy² − (Σy)² = 0.125 − 0.01 = 0.115            (= 23/200)
//   ρ = 0.04 / √(0.365 · 0.115) = (1/25) / √(1679/40000) = 8/√1679
//     = 0.19523812982535205…
const RHO_AAA_BBB = 8 / Math.sqrt(1679);

function fixtureHandCalc(): { tx: string; prices: string } {
  return {
    tx: `
      INSERT INTO transactions (date, asset, action, quantity, price, fees, currency, exchange)
      VALUES
        ('2026-01-01', 'AAA', 'BUY',     10, 100, 0, 'USD', 'IBKR'),
        ('2026-01-01', 'BBB', 'BUY',     20,  50, 0, 'USD', 'IBKR'),
        ('2026-01-01', 'USD', 'DEPOSIT', 2000, NULL, 0, 'USD', 'bank')
    `,
    prices: `
      INSERT INTO prices (ticker, date, price)
      VALUES
        ('AAA', '2026-01-01', 100.0),
        ('AAA', '2026-01-02', 110.0),
        ('AAA', '2026-01-03', 104.5),
        ('AAA', '2026-01-04', 125.4),
        ('AAA', '2026-01-05', 125.4),
        ('AAA', '2026-01-06', 106.59),
        ('BBB', '2026-01-01',  50.0),
        ('BBB', '2026-01-02',  52.5),
        ('BBB', '2026-01-03',  57.75),
        ('BBB', '2026-01-04',  60.6375),
        ('BBB', '2026-01-05',  54.57375),
        ('BBB', '2026-01-06',  54.57375)
    `,
  };
}

MAYBE_SKIP("portfolio_correlation_matrix_sql — Pearson math", () => {
  test("hand-calculated correlation for two tickers over five daily returns", async () => {
    const sql = new SQL(DB_URL!, { max: 1 });
    try {
      await sql.begin(async (tx: any) => {
        await tx.unsafe(DDL.transactions);
        await tx.unsafe(DDL.prices);

        const f = fixtureHandCalc();
        await tx.unsafe(f.tx);
        await tx.unsafe(f.prices);

        const rows = (await tx.unsafe(
          `SELECT asset_a, asset_b, correlation
             FROM portfolio_correlation_matrix_sql($1)
            ORDER BY asset_a, asset_b`,
          [AS_OF],
        )) as { asset_a: unknown; asset_b: unknown; correlation: unknown }[];

        // 2 tickers → all ordered pairs, self-pairs included (current behaviour).
        expect(rows.map((r) => `${r.asset_a}/${r.asset_b}`)).toEqual([
          "AAA/AAA",
          "AAA/BBB",
          "BBB/AAA",
          "BBB/BBB",
        ]);

        // Contract: asset identifiers come back as text, not varchar.
        for (const row of rows) {
          expect(typeof row.asset_a).toBe("string");
          expect(typeof row.asset_b).toBe("string");
        }

        const cross = rows.filter(
          (r) => `${r.asset_a}/${r.asset_b}` === "AAA/BBB",
        );
        expect(cross).toHaveLength(1);
        const rho = Number(cross[0]!.correlation);
        expect(Math.abs(rho - RHO_AAA_BBB)).toBeLessThanOrEqual(1e-9);

        // Mirrored pair and self-pairs (perfect correlation) stay coherent.
        const mirrored = rows.find(
          (r) => `${r.asset_a}/${r.asset_b}` === "BBB/AAA",
        );
        expect(
          Math.abs(Number(mirrored!.correlation) - RHO_AAA_BBB),
        ).toBeLessThanOrEqual(1e-9);

        for (const pair of ["AAA/AAA", "BBB/BBB"]) {
          const selfRow = rows.find((r) => `${r.asset_a}/${r.asset_b}` === pair);
          expect(Math.abs(Number(selfRow!.correlation) - 1.0)).toBeLessThanOrEqual(1e-9);
        }
      });
    } finally {
      await sql.end();
    }
  });
});

MAYBE_SKIP("portfolio_correlation_matrix_sql — CLI JSON contract", () => {
  // No TypeScript adapter queries portfolio_correlation_matrix_sql() directly yet:
  // `diversification` is the command that owns correlation output (it reads the
  // sibling portfolio_diversification_depth_sql). This snapshot pins the canonical
  // {ok, command, data, meta} envelope the matrix will be surfaced through, as
  // required by the AGENTS.md calculation-bug test template.
  test("diversification emits the canonical JSON envelope (empty portfolio)", async () => {
    const proc = Bun.spawn(
      ["bun", "src/cli.ts", "diversification", "--as-of-date", AS_OF],
      {
        cwd: `${import.meta.dir}/..`,
        env: { ...process.env, PORTFOLIO_DB_URL: DB_URL! },
        stdout: "pipe",
        stderr: "pipe",
      },
    );
    const [stdout, stderr] = await Promise.all([
      new Response(proc.stdout).text(),
      new Response(proc.stderr).text(),
    ]);
    const code = await proc.exited;

    expect(code).toBe(0);
    expect(stderr.trim()).toBe("");

    // stdout must be pure JSON — one envelope, nothing else.
    const envelope = JSON.parse(stdout);

    expect(Object.keys(envelope).sort()).toEqual([
      "command",
      "data",
      "meta",
      "ok",
    ]);
    expect(envelope.ok).toBe(true);
    expect(envelope.command).toBe("diversification");

    // Snapshot: empty portfolio has no priced pairs, so correlations are null.
    expect(envelope.data).toEqual({
      as_of_date: AS_OF,
      hhi: 0,
      total_holdings: 0,
      effective_holdings: 0,
      avg_pairwise_correlation: null,
      max_pairwise_correlation: null,
      min_pairwise_correlation: null,
      correlation_weighted_hhi: 0,
    });

    // meta carries a generated_at timestamp; the rest is deterministic here.
    const { generated_at, version, ...restMeta } = envelope.meta;
    expect(Number.isNaN(Date.parse(generated_at))).toBe(false);
    expect(typeof version).toBe("string");
    expect(restMeta).toEqual({
      count: null,
      prices_as_of: null,
      price_age_days: null,
      stale: false,
      needs_recalc: true,
      recalc_warning:
        "Prices were refreshed but daily returns are not recalculated — snapshot commands (status/summary/allocation/cash) and performance may report different values for this date. Run 'recalculate' to sync.",
    });
  });
});

